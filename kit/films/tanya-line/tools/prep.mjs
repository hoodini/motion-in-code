// Build-time data: world-atlas (Natural Earth, public domain) decoded with topojson-client, the traced figure,
// place coordinates (from each place's Wikipedia page), and the four font families inlined from @fontsource.
// -> src/data.js (ES module) and src/fonts.css. No network at render time.
import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import * as topo from 'topojson-client';
const OUT = process.env.OUT || 'src'; mkdirSync(OUT, { recursive: true });
const J = f => JSON.parse(readFileSync(f, 'utf8'));
const r2 = v => Math.round(v * 100) / 100;

// ---------- land 110m: every ring, as flat [lon,lat,...] ----------
function rings(geo) {
  const out = [];
  const polys = geo.type === 'MultiPolygon' ? geo.coordinates : geo.type === 'Polygon' ? [geo.coordinates] : [];
  for (const p of polys) for (const r of p) out.push(r);
  return out;
}
const t110 = J('node_modules/world-atlas/land-110m.json');
const land110 = rings(topo.feature(t110, t110.objects.land).features?.[0]?.geometry ?? topo.feature(t110, t110.objects.land).geometry)
  .filter(r => r.length > 4).map(r => r.flatMap(([a, b]) => [r2(a), r2(b)]));

// ---------- region (50m): land outlines + today's borders, cut to a box around Liozna / Slavuta / St Petersburg ----------
const BOX = [12, 40, 50, 68];
const inBox = ([a, b]) => a >= BOX[0] && a <= BOX[2] && b >= BOX[1] && b <= BOX[3];
function cut(lines) {
  const out = [];
  for (const L of lines) {
    let cur = [];
    for (const p of L) { if (inBox(p)) cur.push(p); else { if (cur.length > 1) out.push(cur); cur = []; } }
    if (cur.length > 1) out.push(cur);
  }
  return out.map(L => L.flatMap(([a, b]) => [r2(a), r2(b)]));
}
const t50 = J('node_modules/world-atlas/land-50m.json');
const lf = topo.feature(t50, t50.objects.land); const lg = lf.features ? lf.features.flatMap(f => rings(f.geometry)) : rings(lf.geometry);
const land50 = cut(lg);
const c50 = J('node_modules/world-atlas/countries-50m.json');
const mesh = topo.mesh(c50, c50.objects.countries, (a, b) => a !== b);
const borders50 = cut(mesh.coordinates);

// ---------- places: coordinates read from Wikipedia during the build (see beatmap.md for the sources) ----------
const PLACES = {
  liozna: [30.8, 55.01666667],            // en.wikipedia.org/wiki/Lyozna
  slavuta: [26.86833333, 50.30277778],    // en.wikipedia.org/wiki/Slavuta (50°18′10″N 26°52′06″E)
  fortress: [30.317, 59.95],              // en.wikipedia.org/wiki/Peter_and_Paul_Fortress
  adelaide: [138.6, -34.9275],            // en.wikipedia.org/wiki/Adelaide
  harare: [31.05222222, -17.82916667],    // en.wikipedia.org/wiki/Harare
  alexandria: [29.8925, 31.1975],         // en.wikipedia.org/wiki/Alexandria
  cairo: [31.23583333, 30.04444444],      // en.wikipedia.org/wiki/Cairo
  e770: [-73.94287, 40.669021]            // en.wikipedia.org/wiki/770_Eastern_Parkway (770 cut only)
};

const FIG = J('fig.json'); const REB = J('reb.json'), B770 = J('770.json');
writeFileSync(OUT + '/data.js', '// generated by prep.mjs — do not edit\n' +
  `export const LAND110=${JSON.stringify(land110)};\nexport const LAND50=${JSON.stringify(land50)};\nexport const BORDERS50=${JSON.stringify(borders50)};\n` +
  `export const PLACES=${JSON.stringify(PLACES)};\nexport const FIG=${JSON.stringify(FIG)};\nexport const REB=${JSON.stringify(REB)};\nexport const B770=${JSON.stringify(B770)};\n`);
console.log('land110 rings', land110.length, 'pts', land110.reduce((a, r) => a + r.length / 2, 0), '| land50 lines', land50.length, 'pts', land50.reduce((a, r) => a + r.length / 2, 0),
  '| borders50 lines', borders50.length, 'pts', borders50.reduce((a, r) => a + r.length / 2, 0), '| fig pts', FIG.pts.length / 2);

// ---------- fonts: @fontsource CSS (keeps unicode-range per subset) with woff2 inlined as data URLs ----------
const FONTS = [['rubik', '900'], ['anton', '400'], ['frank-ruhl-libre', '700'], ['assistant', '700']];
let css = '';
for (const [pkg, w] of FONTS) {
  const src = readFileSync(`node_modules/@fontsource/${pkg}/${w}.css`, 'utf8');
  for (const face of src.match(/@font-face\s*{[^}]*}/g)) {
    const m = face.match(/url\(\.\/files\/([^)]+?-(hebrew|latin)-\d+-normal\.woff2)\)/);
    if (!m) continue;
    const b64 = readFileSync(`node_modules/@fontsource/${pkg}/files/${m[1]}`).toString('base64');
    css += face.replace(/src:[^;]+;/, `src: url(data:font/woff2;base64,${b64}) format('woff2');`).replace(/font-display:[^;]+;/, 'font-display: block;') + '\n';
  }
}
writeFileSync(OUT + '/fonts.css', css);
console.log('fonts.css', (css.length / 1024).toFixed(0) + ' KB', (css.match(/@font-face/g) || []).length, 'faces');

